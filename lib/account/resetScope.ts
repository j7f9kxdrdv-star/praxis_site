// ─── What "reset my account" actually touches ────────────────────────────────
//
// ONE LIST, BECAUSE A RESET THAT MISSES A TABLE IS WORSE THAN NO RESET. A
// student who presses the button and is told "done" while a thousand card
// schedules survive gets a deck that claims to be new and then serves reviews
// from a history they were told was gone. The failure is silent by nature: the
// UI has nothing to notice.
//
// So the tables live here rather than inline in the route, every table the app
// touches is classified, and resetScope.test.ts fails if a new one appears in
// the codebase without being put in one of these buckets. Adding a table to the
// app is the moment someone has to decide whether a reset should clear it.
//
// DELETE ORDER IS HISTORY FIRST, then the state derived from it, then what the
// analytics layer inferred. No foreign keys currently tie these together, so
// the order is for readability rather than necessity; if one is added later,
// this order is already the safe one.

export type ResetScope = "progress" | "everything";

/**
 * Per-user study data, cleared by both scopes.
 *
 * Every one of these is regenerated by studying. Nothing here is a record the
 * student authored or would miss as a document.
 */
export const USER_DATA_TABLES = [
  // Raw history.
  "flashcard_reviews",
  "question_attempts",
  "practice_sessions",
  "daily_activity",
  "lesson_progress",
  // Scheduling state built from that history.
  "flashcard_user_state",
  "review_schedule",
  "study_plan_tasks",
  // What the analytics and reports layer inferred from both.
  "learner_state_snapshots",
  "learner_events",
  "performance_reports",
  "user_insight_briefs",
] as const;

/**
 * Per-user tables a reset deliberately LEAVES ALONE, and why.
 *
 * official_mcat_scores is the one worth arguing about. It holds real exam
 * results the student typed in, which a study reset has no business destroying:
 * starting a new prep cycle does not un-sit an exam. If someone wants those
 * gone, that is a separate, explicit action.
 */
export const KEPT_USER_TABLES: Record<string, string> = {
  profiles: "the account itself; onboarding fields are cleared, identity is not",
  official_mcat_scores: "real exam results, not study progress",
  support_messages: "correspondence with Praxist, not study progress",
};

/** Shared content and marketing tables that hold no per-user progress. */
export const NON_USER_TABLES: Record<string, string> = {
  flashcards: "deck content",
  flashcard_decks: "deck content",
  questions: "question bank",
  passages: "question bank",
  lessons: "course content",
  waitlist_signups: "marketing capture, not an account",
};

/**
 * Profile columns returned to their schema defaults when onboarding is reset.
 *
 * Only the answers onboarding collects. Name, email, timezone and day_start_hour
 * describe the person and their device, not their progress, and survive both
 * scopes. The limits are the schema defaults of 25 and 150, which matters
 * because a hand-edited limit (one live account was sitting at 5000) is exactly
 * the kind of thing a "start over" is expected to undo.
 */
export const ONBOARDING_DEFAULTS = {
  onboarding_completed: false,
  mcat_test_date: null,
  target_mcat_score: null,
  study_hours_per_week: null,
  weak_sections: null,
  daily_new_card_limit: 25,
  daily_review_limit: 150,
  weekly_question_goal: 100,
} as const;

/** The profile patch for a scope, or null when the profile is untouched. */
export function profilePatchFor(scope: ResetScope): typeof ONBOARDING_DEFAULTS | null {
  return scope === "everything" ? ONBOARDING_DEFAULTS : null;
}

/** Human wording for the confirmation screen, so UI and API cannot disagree. */
export function describeScope(scope: ResetScope): { title: string; effect: string } {
  return scope === "everything"
    ? {
        title: "Start over completely",
        effect:
          "Clears all study progress and sends you back through setup. Your login and name stay.",
      }
    : {
        title: "Reset my progress",
        effect:
          "Clears all study progress. Your exam date, study hours and daily limits stay as they are.",
      };
}

export function isResetScope(value: unknown): value is ResetScope {
  return value === "progress" || value === "everything";
}
