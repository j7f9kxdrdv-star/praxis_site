import { all } from "../backfill/record.mjs";
const C=await all("concepts","id,slug,canonical_name,status");
const byId=new Map(C.map(c=>[c.id,c]));
const QC=await all("question_concepts","question_id,concept_id,role");
const Q=await all("questions","id,topic,content_category,subtopic");
const qById=new Map(Q.map(q=>[q.id,q]));
const CCC=await all("concept_content_categories","concept_id,content_category");
const cats={}; CCC.forEach(r=>(cats[r.concept_id]=cats[r.concept_id]||new Set()).add(r.content_category));
console.log("=== A. category-incompatible mappings ===");
const bad=QC.filter(m=>!cats[m.concept_id]?.has(qById.get(m.question_id)?.content_category));
console.log(`count: ${bad.length}`);
bad.slice(0,12).forEach(m=>{const q=qById.get(m.question_id),c=byId.get(m.concept_id);
  console.log(`  [${m.role}] ${q.topic} / "${q.subtopic}"`);
  console.log(`      question category: ${q.content_category}`);
  console.log(`      concept ${c.canonical_name} has: ${[...(cats[c.id]||[])].join(" | ")||"(none)"}`);});
console.log("\n=== B. one PRIMARY per question, role-aware ===");
const prim={}; QC.filter(m=>m.role==="PRIMARY").forEach(m=>prim[m.question_id]=(prim[m.question_id]||0)+1);
console.log(`questions with >1 PRIMARY: ${Object.values(prim).filter(n=>n>1).length}`);
console.log(`total PRIMARY rows: ${QC.filter(m=>m.role==="PRIMARY").length} | SECONDARY: ${QC.filter(m=>m.role==="SECONDARY").length}`);
console.log("\n=== C. what the 1-question heuristic now catches ===");
const per={}; QC.forEach(m=>(per[m.concept_id]=per[m.concept_id]||[]).push(m.question_id));
const imcv=new Set(Q.filter(q=>["The Immune System","The Cardiovascular System"].includes(q.topic)).map(q=>q.id));
const hits=Object.entries(per).filter(([,qs])=>qs.length===1&&imcv.has(qs[0]));
console.log(`concepts matching "exactly 1 question, in immune or cardio": ${hits.length}`);
const dep=hits.filter(([c])=>byId.get(c).status==="DEPRECATED").length;
const durable=hits.filter(([c])=>byId.get(c).status!=="DEPRECATED");
console.log(`  of which DEPRECATED (old labels): ${dep}`);
console.log(`  of which still ACTIVE: ${durable.length}`);
durable.slice(0,12).forEach(([c,qs])=>console.log(`     ${byId.get(c).canonical_name}  (${qById.get(qs[0]).topic})`));
